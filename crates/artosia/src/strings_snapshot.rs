fn dump_in(indonesian: bool) -> String {
    set_indonesian(indonesian);
    let out = dump();
    set_indonesian(false);
    out
}

fn same(have: &str, fixture: &str, name: &str) {
    let fixture = fixture.replace("\r\n", "\n");
    if have != fixture {
        let first = have.lines().zip(fixture.lines()).find(|(a, b)| a != b);
        panic!("{name} differs; first difference: {first:?}");
    }
}

#[test]
fn english_is_unchanged() {
    let have = dump_in(false);
    if std::env::var("ARTOSIA_WRITE_SNAPSHOT").is_ok() {
        std::fs::write(concat!(env!("CARGO_MANIFEST_DIR"), "/testdata/strings-en.txt"), &have).unwrap_or_else(|error| panic!("{error}"));
    }
    same(&have, include_str!("../testdata/strings-en.txt"), "English");
}

